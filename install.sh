#!/usr/bin/env bash
# Install Datawatch for the current user: app, launcher, icon and autostart.
#
#   ./install.sh                 install + start at login (hidden in background)
#   ./install.sh --show-window   install + start at login with the window open
#   ./install.sh --no-autostart  install only, no login autostart
#   ./install.sh --systemd       install a systemd --user service instead of autostart
#   ./install.sh --uninstall     same as ./uninstall.sh
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_ID="io.datawatch.App"

DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
BIN_DIR="$HOME/.local/bin"
BIN="$BIN_DIR/datawatch"
APP_HOME="$DATA_HOME/datawatch"          # python package lives here
APPLICATIONS_DIR="$DATA_HOME/applications"
AUTOSTART_DIR="$CONFIG_HOME/autostart"
ICON_DIR="$DATA_HOME/icons/hicolor/scalable/apps"
SYSTEMD_DIR="$CONFIG_HOME/systemd/user"

HIDDEN=1
AUTOSTART=1
SYSTEMD=0

usage() {
    sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'
}

for arg in "$@"; do
    case "$arg" in
        --show-window) HIDDEN=0 ;;
        --no-autostart) AUTOSTART=0 ;;
        --systemd) SYSTEMD=1; AUTOSTART=0 ;;
        --uninstall) exec "$SRC/uninstall.sh" ;;
        -h|--help) usage; exit 0 ;;
        *) echo "install.sh: unknown option '$arg' (try --help)" >&2; exit 2 ;;
    esac
done

# --------------------------------------------------------------------------
# 1. runtime check
# --------------------------------------------------------------------------
if ! python3 - <<'PY' >/dev/null 2>&1
import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Gtk, Adw  # noqa
import cairo  # noqa
PY
then
    cat >&2 <<'MSG'
error: the GTK 4 / libadwaita Python bindings (or pycairo) are missing.

  Arch / CachyOS:  sudo pacman -S python-gobject gtk4 libadwaita python-cairo
  Debian / Ubuntu: sudo apt install python3-gi gir1.2-gtk-4.0 gir1.2-adw-1 python3-cairo
MSG
    exit 1
fi

echo "Installing Datawatch to $APP_HOME"

# --------------------------------------------------------------------------
# 2. copy the package
# --------------------------------------------------------------------------
mkdir -p "$APP_HOME"
rm -rf "${APP_HOME:?}/datawatch"
cp -r "$SRC/datawatch" "$APP_HOME/datawatch"
find "$APP_HOME/datawatch" -name '__pycache__' -type d -prune -exec rm -rf {} + 2>/dev/null || true

# --------------------------------------------------------------------------
# 3. launcher
# --------------------------------------------------------------------------
mkdir -p "$BIN_DIR"
cat > "$BIN" <<EOF
#!/bin/sh
# Generated by Datawatch's install.sh - runs the installed copy of the app.
export PYTHONPATH="\${XDG_DATA_HOME:-\$HOME/.local/share}/datawatch\${PYTHONPATH:+:\$PYTHONPATH}"
exec python3 -m datawatch "\$@"
EOF
chmod 0755 "$BIN"
echo "  launcher   -> $BIN"

# --------------------------------------------------------------------------
# 4. icon + menu entry
# --------------------------------------------------------------------------
mkdir -p "$ICON_DIR" "$APPLICATIONS_DIR"
if [[ -f "$SRC/packaging/datawatch.svg" ]]; then
    install -m 0644 "$SRC/packaging/datawatch.svg" "$ICON_DIR/datawatch.svg"
    echo "  icon       -> $ICON_DIR/datawatch.svg"
fi

sed "s|@EXEC@|$BIN|g" "$SRC/packaging/datawatch.desktop" \
    > "$APPLICATIONS_DIR/$APP_ID.desktop"
chmod 0644 "$APPLICATIONS_DIR/$APP_ID.desktop"
echo "  menu entry -> $APPLICATIONS_DIR/$APP_ID.desktop"

command -v update-desktop-database >/dev/null && \
    update-desktop-database "$APPLICATIONS_DIR" >/dev/null 2>&1 || true
command -v gtk-update-icon-cache >/dev/null && \
    gtk-update-icon-cache -q -t "$DATA_HOME/icons/hicolor" >/dev/null 2>&1 || true

# --------------------------------------------------------------------------
# 5. start at login
# --------------------------------------------------------------------------
if [[ "$AUTOSTART" -eq 1 ]]; then
    mkdir -p "$AUTOSTART_DIR"
    exec_line="$BIN"
    [[ "$HIDDEN" -eq 1 ]] && exec_line="$BIN --hidden"
    sed "s|@EXEC@|$exec_line|g" "$SRC/packaging/datawatch.desktop" \
        > "$AUTOSTART_DIR/datawatch.desktop"
    chmod 0644 "$AUTOSTART_DIR/datawatch.desktop"
    if [[ "$HIDDEN" -eq 1 ]]; then
        echo "  autostart  -> $AUTOSTART_DIR/datawatch.desktop (starts in background)"
    else
        echo "  autostart  -> $AUTOSTART_DIR/datawatch.desktop (starts with the window open)"
    fi
elif [[ "$SYSTEMD" -eq 1 ]]; then
    mkdir -p "$SYSTEMD_DIR"
    exec_line="$BIN"
    [[ "$HIDDEN" -eq 1 ]] && exec_line="$BIN --hidden"
    sed -e "s|@EXEC@|$exec_line|g" -e "s|@PROJECT@|$SRC|g" \
        "$SRC/packaging/datawatch.service" > "$SYSTEMD_DIR/datawatch.service"
    chmod 0644 "$SYSTEMD_DIR/datawatch.service"
    systemctl --user daemon-reload 2>/dev/null || true
    systemctl --user enable --now datawatch.service 2>/dev/null || true
    echo "  service    -> $SYSTEMD_DIR/datawatch.service"
fi

cat <<EOF

Datawatch installed.

  Run it now:        datawatch
  Start hidden:      datawatch --hidden
  Open a tab:        datawatch --page history
  Preferences:       datawatch --settings
  Stop autostart:    ./uninstall.sh --keep-data

Data is kept in ${XDG_DATA_HOME:-$HOME/.local/share}/datawatch/history.sqlite3
Settings live in ${XDG_CONFIG_HOME:-$HOME/.config}/datawatch/config.json

Re-run ./install.sh after pulling updates to refresh the installed copy.
EOF
