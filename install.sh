#!/usr/bin/env bash
# Install Data Monitor for the current user: app, launcher, icon and autostart.
#
#   ./install.sh                 install + start at login (hidden in background)
#   ./install.sh --show-window   install + start at login with the window open
#   ./install.sh --no-autostart  install only, no login autostart
#   ./install.sh --systemd       use a systemd --user service instead of autostart
#   ./install.sh --uninstall     same as ./uninstall.sh
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_ID="io.datamonitor.App"

DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
BIN_DIR="$HOME/.local/bin"
BIN="$BIN_DIR/datamonitor"
LEGACY_BIN="$BIN_DIR/datawatch"          # pre-1.2 alias, kept for old habits
APP_HOME="$DATA_HOME/datamonitor"        # python package lives here
CONFIG_DIR="$CONFIG_HOME/datamonitor"
APPLICATIONS_DIR="$DATA_HOME/applications"
AUTOSTART_DIR="$CONFIG_HOME/autostart"
ICON_DIR="$DATA_HOME/icons/hicolor/scalable/apps"
SYSTEMD_DIR="$CONFIG_HOME/systemd/user"

# Locations used by Datawatch <= 1.1 (migrated / cleaned up below).
LEGACY_APP_HOME="$DATA_HOME/datawatch"
LEGACY_CONFIG_DIR="$CONFIG_HOME/datawatch"

HIDDEN=1
AUTOSTART=1
SYSTEMD=0

usage() {
    sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'
}

for arg in "$@"; do
    case "$arg" in
        --show-window) HIDDEN=0 ;;
        --no-autostart) AUTOSTART=0 ;;
        --systemd) SYSTEMD=1; AUTOSTART=0 ;;
        --uninstall) exec "$SRC/uninstall.sh" ;;
        -h|--help) usage; exit 0 ;;
        *) echo "install.sh: unknown option '$arg' (try --help)" >&2; exit 2 ;;
    esac
done

# --------------------------------------------------------------------------
# 1. runtime check
# --------------------------------------------------------------------------
if ! python3 - <<'PY' >/dev/null 2>&1
import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Gtk, Adw  # noqa
import cairo  # noqa
PY
then
    cat >&2 <<'MSG'
error: the GTK 4 / libadwaita Python bindings (or pycairo) are missing.

  Arch / CachyOS:  sudo pacman -S python-gobject gtk4 libadwaita python-cairo
  Debian / Ubuntu: sudo apt install python3-gi gir1.2-gtk-4.0 gir1.2-adw-1 python3-cairo
MSG
    exit 1
fi

echo "Installing Data Monitor to $APP_HOME"

# --------------------------------------------------------------------------
# 2. migrate a previous "Datawatch" (<= 1.1) install
# --------------------------------------------------------------------------
if [[ -d "$LEGACY_CONFIG_DIR" && ! -e "$CONFIG_DIR" ]]; then
    mv "$LEGACY_CONFIG_DIR" "$CONFIG_DIR"
    echo "  migrated settings $LEGACY_CONFIG_DIR -> $CONFIG_DIR"
fi
mkdir -p "$APP_HOME"
if [[ -f "$LEGACY_APP_HOME/history.sqlite3" && ! -f "$APP_HOME/history.sqlite3" ]]; then
    mv "$LEGACY_APP_HOME/history.sqlite3" "$APP_HOME/history.sqlite3"
    echo "  migrated history  -> $APP_HOME/history.sqlite3"
fi

# --------------------------------------------------------------------------
# 3. copy the package
# --------------------------------------------------------------------------
rm -rf "${APP_HOME:?}/datamonitor"
cp -r "$SRC/datamonitor" "$APP_HOME/datamonitor"
find "$APP_HOME/datamonitor" -name '__pycache__' -type d -prune -exec rm -rf {} + 2>/dev/null || true

# --------------------------------------------------------------------------
# 4. launcher (+ pre-1.2 alias)
# --------------------------------------------------------------------------
mkdir -p "$BIN_DIR"
cat > "$BIN" <<EOF
#!/bin/sh
# Generated by Data Monitor's install.sh - runs the installed copy of the app.
export PYTHONPATH="\${XDG_DATA_HOME:-\$HOME/.local/share}/datamonitor\${PYTHONPATH:+:\$PYTHONPATH}"
exec python3 -m datamonitor "\$@"
EOF
chmod 0755 "$BIN"
cp "$BIN" "$LEGACY_BIN"
chmod 0755 "$LEGACY_BIN"
echo "  launcher   -> $BIN  (alias: $LEGACY_BIN)"

# --------------------------------------------------------------------------
# 5. icon + menu entry
# --------------------------------------------------------------------------
mkdir -p "$ICON_DIR" "$APPLICATIONS_DIR"
if [[ -f "$SRC/packaging/datamonitor.svg" ]]; then
    install -m 0644 "$SRC/packaging/datamonitor.svg" "$ICON_DIR/datamonitor.svg"
    echo "  icon       -> $ICON_DIR/datamonitor.svg"
fi

sed "s|@EXEC@|$BIN|g" "$SRC/packaging/datamonitor.desktop" \
    > "$APPLICATIONS_DIR/$APP_ID.desktop"
chmod 0644 "$APPLICATIONS_DIR/$APP_ID.desktop"
echo "  menu entry -> $APPLICATIONS_DIR/$APP_ID.desktop"

command -v update-desktop-database >/dev/null && \
    update-desktop-database "$APPLICATIONS_DIR" >/dev/null 2>&1 || true
command -v gtk-update-icon-cache >/dev/null && \
    gtk-update-icon-cache -q -t "$DATA_HOME/icons/hicolor" >/dev/null 2>&1 || true

# --------------------------------------------------------------------------
# 6. start at login
# --------------------------------------------------------------------------
if [[ "$AUTOSTART" -eq 1 ]]; then
    mkdir -p "$AUTOSTART_DIR"
    exec_line="$BIN"
    [[ "$HIDDEN" -eq 1 ]] && exec_line="$BIN --hidden"
    sed "s|@EXEC@|$exec_line|g" "$SRC/packaging/datamonitor.desktop" \
        > "$AUTOSTART_DIR/datamonitor.desktop"
    chmod 0644 "$AUTOSTART_DIR/datamonitor.desktop"
    if [[ "$HIDDEN" -eq 1 ]]; then
        echo "  autostart  -> $AUTOSTART_DIR/datamonitor.desktop (starts in background)"
    else
        echo "  autostart  -> $AUTOSTART_DIR/datamonitor.desktop (starts with the window open)"
    fi
elif [[ "$SYSTEMD" -eq 1 ]]; then
    mkdir -p "$SYSTEMD_DIR"
    exec_line="$BIN"
    [[ "$HIDDEN" -eq 1 ]] && exec_line="$BIN --hidden"
    sed -e "s|@EXEC@|$exec_line|g" -e "s|@PROJECT@|$SRC|g" \
        "$SRC/packaging/datamonitor.service" > "$SYSTEMD_DIR/datamonitor.service"
    chmod 0644 "$SYSTEMD_DIR/datamonitor.service"
    systemctl --user daemon-reload 2>/dev/null || true
    systemctl --user enable --now datamonitor.service 2>/dev/null || true
    echo "  service    -> $SYSTEMD_DIR/datamonitor.service"
fi

# --------------------------------------------------------------------------
# 7. clean up artifacts of Datawatch <= 1.1
# --------------------------------------------------------------------------
rm -f "$APPLICATIONS_DIR/io.datawatch.App.desktop"
rm -f "$AUTOSTART_DIR/datawatch.desktop"
rm -f "$ICON_DIR/datawatch.svg"
rm -f "$SYSTEMD_DIR/datawatch.service"
if command -v systemctl >/dev/null; then
    systemctl --user disable --now datawatch.service >/dev/null 2>&1 || true
    systemctl --user daemon-reload >/dev/null 2>&1 || true
fi
rm -rf "$LEGACY_APP_HOME/datawatch"      # old installed copy of the code
if [[ -d "$LEGACY_APP_HOME" ]]; then
    # Keep the directory only if an un-migrated history file still sits there.
    if [[ -z "$(ls -A "$LEGACY_APP_HOME" 2>/dev/null)" ]]; then
        rmdir "$LEGACY_APP_HOME"
    fi
fi

cat <<EOF

Data Monitor installed.

  Run it now:        datamonitor
  Start hidden:      datamonitor --hidden
  Open a tab:        datamonitor --page history
  Preferences:       datamonitor --settings
  Stop autostart:    ./uninstall.sh --keep-data
  (the old "datawatch" command still works as an alias)

Data is kept in ${XDG_DATA_HOME:-$HOME/.local/share}/datamonitor/history.sqlite3
Settings live in ${XDG_CONFIG_HOME:-$HOME/.config}/datamonitor/config.json

Re-run ./install.sh after pulling updates to refresh the installed copy.
EOF
